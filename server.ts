import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json({ limit: '25mb' }));

// Helper to obtain initialized Gemini client
function getGenAIClient() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error('GEMINI_API_KEY environment variable is missing.');
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

// 1. Streaming Chat Endpoint (SSE)
app.post('/api/chat', async (req, res) => {
  let isClientClosed = false;
  req.on('close', () => {
    isClientClosed = true;
  });

  // Prepare SSE headers
  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');
  res.flushHeaders?.();

  try {
    const { messages, systemInstruction, temperature = 0.7 } = req.body;

    if (!messages || !Array.isArray(messages) || messages.length === 0) {
      res.write(`data: ${JSON.stringify({ error: 'No messages provided.' })}\n\n`);
      res.end();
      return;
    }

    const ai = getGenAIClient();

    // Map messages to Gemini format: role must be 'user' or 'model'
    const formattedContents = messages.map((m: { role: string; content: string }) => ({
      role: m.role === 'assistant' ? 'model' : 'user',
      parts: [{ text: m.content || '' }],
    }));

    const responseStream = await ai.models.generateContentStream({
      model: 'gemini-3.8-flash',
      contents: formattedContents,
      config: {
        systemInstruction: systemInstruction || 'You are Angel, an intelligent, empathetic, and exceptionally capable AI assistant. Answer concisely, format rich code blocks with language labels, and maintain a thoughtful, helpful, and friendly tone.',
        temperature: typeof temperature === 'number' ? Math.max(0, Math.min(1, temperature)) : 0.7,
      },
    });

    for await (const chunk of responseStream) {
      if (isClientClosed) {
        break;
      }
      const text = chunk.text;
      if (text) {
        res.write(`data: ${JSON.stringify({ text })}\n\n`);
      }
    }

    if (!isClientClosed) {
      res.write(`data: ${JSON.stringify({ done: true })}\n\n`);
      res.end();
    }
  } catch (error: any) {
    console.error('Chat generation error:', error);
    const errorMessage = error?.message || 'An error occurred while generating a response.';
    if (!isClientClosed) {
      res.write(`data: ${JSON.stringify({ error: errorMessage })}\n\n`);
      res.end();
    }
  }
});

// Cooldown tracker for Gemini TTS free-tier rate limits (3 requests / minute)
let ttsCooldownUntil = 0;

// 2. High-Quality Text-to-Speech Endpoint (Gemini 3.8 Flash Lite TTS with smart fallback)
app.post('/api/tts', async (req, res) => {
  try {
    const { text, voice = 'Kore' } = req.body;

    if (!text || typeof text !== 'string') {
      res.status(400).json({ error: 'Text string is required.' });
      return;
    }

    // If currently in cooldown due to free-tier quota limits, immediately instruct client to use browser speech
    if (Date.now() < ttsCooldownUntil) {
      const remainingSec = Math.ceil((ttsCooldownUntil - Date.now()) / 1000);
      res.json({
        fallbackToBrowser: true,
        message: `Gemini TTS free-tier quota reached (3 req/min). Using device voice (${remainingSec}s cooldown).`,
      });
      return;
    }

    const ai = getGenAIClient();
    const validVoices = ['Kore', 'Puck', 'Charon', 'Fenrir', 'Zephyr'];
    const chosenVoice = validVoices.includes(voice) ? voice : 'Kore';

    // Limit text chunk for TTS to prevent excessive processing time and preserve quota
    const cleanText = text.slice(0, 500).replace(/```[\s\S]*?```/g, 'Code block omitted for audio.');

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-lite-tts',
      contents: [
        {
          role: 'user',
          parts: [{ text: cleanText }],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: chosenVoice },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;

    if (!base64Audio) {
      res.json({
        fallbackToBrowser: true,
        message: 'No audio generated by model. Using device speech.',
      });
      return;
    }

    res.json({
      audio: base64Audio,
      mimeType: 'audio/wav',
    });
  } catch (error: any) {
    const errorString = String(error?.message || error || '');
    const isRateLimit =
      error?.status === 429 ||
      error?.code === 429 ||
      errorString.includes('429') ||
      errorString.includes('quota') ||
      errorString.includes('RESOURCE_EXHAUSTED');

    if (isRateLimit) {
      // Cooldown for 60 seconds to respect free-tier 3 req/min limit
      ttsCooldownUntil = Date.now() + 60000;
      console.warn('Gemini TTS free-tier quota limit reached (3 req/min). Gracefully instructing client to use device speech synthesis.');
      res.json({
        fallbackToBrowser: true,
        message: 'Gemini TTS quota exceeded. Using device voice fallback.',
      });
      return;
    }

    console.warn('TTS request error, using browser speech fallback:', errorString.slice(0, 150));
    res.json({
      fallbackToBrowser: true,
      message: 'TTS generation unavailable. Using device voice fallback.',
    });
  }
});

// 3. Audio Transcription Endpoint (Gemini 3.5 Transcribe fallback for voice audio)
app.post('/api/transcribe', async (req, res) => {
  try {
    const { audioData, mimeType = 'audio/webm' } = req.body;

    if (!audioData) {
      res.status(400).json({ error: 'Audio data is required.' });
      return;
    }

    const ai = getGenAIClient();

    const response = await ai.models.generateContent({
      model: 'gemini-3.5-transcribe',
      contents: [
        {
          parts: [
            {
              inlineData: {
                mimeType,
                data: audioData,
              },
            },
            {
              text: 'Transcribe this voice audio accurately. Return only the transcription text, without any introductory or concluding comments.',
            },
          ],
        },
      ],
    });

    const text = response.text || '';
    res.json({ text: text.trim() });
  } catch (error: any) {
    console.error('Transcription error:', error);
    res.status(500).json({ error: error?.message || 'Audio transcription failed.' });
  }
});

// 4. Multimodal Vision Analysis Endpoint (Gemini 3.8 Flash)
app.post('/api/vision', async (req, res) => {
  try {
    const { imageData, mimeType = 'image/jpeg', prompt = 'Examine and describe this image in detail, noting key objects, text, context, and insights.' } = req.body;

    if (!imageData) {
      res.status(400).json({ error: 'Image data is required.' });
      return;
    }

    const ai = getGenAIClient();

    // Strip data URL header if present
    const cleanBase64 = imageData.includes(',') ? imageData.split(',')[1] : imageData;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: [
        {
          role: 'user',
          parts: [
            {
              inlineData: {
                mimeType,
                data: cleanBase64,
              },
            },
            {
              text: prompt,
            },
          ],
        },
      ],
      config: {
        systemInstruction: 'You are NOVA AI Visual Lens, an advanced multimodal computer vision assistant. Provide sharp, structured, insightful observations. Include identified subjects, text (OCR if present), color palette, and helpful actionable notes.',
        temperature: 0.4,
      },
    });

    const text = response.text || 'No description could be generated for this image.';
    res.json({ text });
  } catch (error: any) {
    console.error('Vision analysis error:', error);
    res.status(500).json({ error: error?.message || 'Visual analysis failed.' });
  }
});

// 5. Service Status & Connectivity Endpoint
app.get('/api/status', (_req, res) => {
  const hasKey = !!process.env.GEMINI_API_KEY;
  res.json({
    status: hasKey ? 'online' : 'unconfigured',
    geminiConnected: hasKey,
    activeModel: 'gemini-3.8-flash',
    visionSupported: true,
    speechSupported: true,
  });
});

// 6. Mount Vite middleware in development or serve static in production
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: {
        middlewareMode: true,
        hmr: false,
      },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Server listening on port ${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
